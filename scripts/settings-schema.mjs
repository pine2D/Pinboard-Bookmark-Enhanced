// Single source of truth for non-AI-provider extension settings:
//   - `shared.js`: `SETTINGS_DEFAULTS`, `PRIME_EXCLUDED_KEYS`, `API_KEY_FIELDS`
//   - `options-backup.js`: `PBP_BACKUP_ENUMS`, `PBP_BACKUP_DROP_ON_UNKNOWN_ENUM`
//   - `options.js`: `PANEL_DEFAULTS`, `fieldMap`, `checkMap`, `collectSettingsFromForm`
//   - `options.html`: static default attributes (`checked`, `value=`, `<select>`)
//
// Built-in AI provider settings live in `scripts/ai-providers-source.mjs`.
// Together, `SETTINGS_SCHEMA` + `AI_PROVIDERS` cover 100% of `SETTINGS_DEFAULTS`.
// After editing this schema, run:
//   node scripts/sync-settings-schema.mjs --write

function deepFreeze(value) {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}

