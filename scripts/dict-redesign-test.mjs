                // offline to A's kept items (no AI, no detector).
                fields.scriptDrops = await scriptCheckDrops(items.map(item => [item.explanation, item.translation].filter(Boolean).join("\n\n")),
                  preflight.target, result.value.learning?.language || preflight.target.lang);
