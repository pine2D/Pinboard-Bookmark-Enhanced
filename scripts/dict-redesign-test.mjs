export function checkEstimates(plan, estimates) {
  const counts = plannedCounts(plan), totals = {};
  for (const model of plan.models) for (const [name, s] of Object.entries(ESTIMATE_SCENARIOS)) {
    const row = estimates?.[model.id]?.[name]?.result;
    if (estimates[model.id][name].snapshot?.stale !== false || row?.status !== "estimated" || row.model !== model.id ||
        row.requests !== counts.models[model.id].clicks || row.input_tokens !== s.input || row.output_tokens !== s.output ||
        !Number.isFinite(Number(row.total_usd))) fail("estimate_unknown_or_mismatched");
    totals[name] = (totals[name] || 0) + Number(row.total_usd);
  }
  return Object.fromEntries(Object.entries(totals).map(([name, value]) => [name, Math.round(value * 1e4) / 1e4]));
}

