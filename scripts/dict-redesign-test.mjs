export function authorizeScope(plan, round = ROUND) {
  const bad = code => fail("unauthorized_scope_" + code);
  // Schema 3 is a round of this authorization: exactly the pinned round.
  // Schema 2 carries no round at all (reserve, freeze and report read it).
  const r = plan?.schema === 3 ? round : null;
  if (!((plan?.schema === 2 && !Object.hasOwn(plan, "round")) || (r && isDeepStrictEqual(plan.round, plain(r)))) ||
      plan.scope !== AUTHORIZATION.scope || plan.keyVariable !== KEY_VARIABLE) bad("identity");
  if (checkBaseUrl(plan.baseUrl) !== AUTHORIZATION.endpoint) bad("endpoint");
  const ids = plan.models.map(model => model.id);
  if (!ids.length || new Set(ids).size !== ids.length || ids.some(id => !Object.hasOwn(AUTHORIZATION.models, id)) ||
      (r && !isDeepStrictEqual([...ids].sort(), [...r.models].sort()))) bad("models");
  // Authorized caps are recorded as authorized (a round's own where it moves
  // one); the stop gate is exactly 80%.
  const cap = id => r?.caps?.[id] ?? AUTHORIZATION.models[id];
  if (plan.models.some(model => model.capUSD !== cap(model.id) || model.stopUSD !== stopOf(cap(model.id)))) bad("model_cap");
  if (plan.budget.totalUSD !== AUTHORIZATION.totalUSD || plan.budget.stopFraction !== STOP_FRACTION || plan.budget.stopUSD !== stopOf(AUTHORIZATION.totalUSD)) bad("total_cap");
  const l = plan.limits;
  if (l.outputTokens > AUTHORIZATION.outputTokens || l.retries !== AUTHORIZATION.retries || l.fallbacks !== AUTHORIZATION.fallbacks ||
      l.httpPerCase > 4 || l.inputBytes > 24576 || (r && l.timeoutMs !== r.timeoutMs)) bad("limits");
  const allowed = new Map(WORDS.map(word => [word.id, word]));
  if (plan.words.some(word => !isDeepStrictEqual({ ...word }, { ...allowed.get(word.id) }) ||
      !AUTHORIZATION.sourceLanguages.includes(word.sourceLanguage) || !AUTHORIZATION.targets.includes(word.target)) ||
      (r && !isDeepStrictEqual(plan.words, plain(WORDS)))) bad("words");
  const set = id => plan.words.find(word => word.id === id)?.set;
  if (plan.phases.pilot.words.some(id => set(id) !== "dev") || plan.phases.full.words.some(id => set(id) !== "holdout")) bad("phase_words");
  if (plan.phases.pilot.models.length !== (r ? 0 : 2) || [...plan.phases.pilot.models, ...plan.phases.full.models].some(id => !ids.includes(id)) ||
      (r && !isDeepStrictEqual([...plan.phases.full.models].sort(), [...ids].sort()))) bad("phase_models");
  // Probe: every authorized model, exactly one base entry on the dev word.
  const probe = plan.phases.probe;
  if (!probe || !isDeepStrictEqual([...probe.models].sort(), [...ids].sort()) || !isDeepStrictEqual(probe.words, [PROBE_WORD]) ||
      set(PROBE_WORD) !== "dev" || !isDeepStrictEqual(probe.arms, ["entry"])) bad("probe");
  if (!isDeepStrictEqual(Object.keys(plan.phases).sort(), ["full", "pilot", "probe"])) bad("phases");
  if (Object.keys(plan.arms).some(arm => !AUTHORIZATION.arms.includes(arm))) bad("arms");
  if (plan.lCount !== 4 || plan.lCandidates.some(id => set(id) !== "holdout") || (r && !isDeepStrictEqual(plan.lCandidates, [...L_CANDIDATES]))) bad("literature");
  if (!isDeepStrictEqual([...plan.aCategories], [...A_CATEGORIES])) bad("categories");
  // A round's arms are the baseline's: its prototype is the one frozen there,
  // and its product is the pinned one.
  if (r && !isDeepStrictEqual(plan.fingerprints?.proto, plain(r.baseline.proto))) bad("proto");
  if (r && plan.fingerprints?.product !== r.product) bad("product");
  return true;
}
export function verifyPlan(plan, round = ROUND) {
  const { planHash, ...body } = plan;
  if (hash(body) !== planHash) fail("plan_tampered");
  authorizeScope(plan, round);
  return plan;
}

export const armOrderFlip = (model, wordId, phase) => parseInt(hash([THRESHOLDS.orderSeed, phase, model, wordId]).slice(0, 8), 16) % 2 === 1;
// Planned clicks. Before evidence exists, literature is counted at its upper
// bound (four holdout words, both dev words).
export function plannedCases(plan, phase, evidence = null) {
  if (phase === "probe") return plan.phases.probe.models.flatMap(model => plan.phases.probe.words.map(wordId =>
    ({ caseId: ["probe", model, wordId, "entry"].join(":"), phase, model, wordId, arm: "entry", category: "entry" })));
  const cases = [], lWords = evidence?.lWords?.[phase] ?? (phase === "full" ? plan.lCandidates.slice(0, plan.lCount) : plan.phases.pilot.words);
  for (const model of plan.phases[phase].models) for (const wordId of plan.phases[phase].words) {
    const id = (arm, category = "") => [phase, model, wordId, arm, category].filter(Boolean).join(":");
    // Entry first (every arm shares it); then B before or after the A block
    // and L-B before or after L-A, by a pre-registered seeded coin per word.
    const flip = armOrderFlip(model, wordId, phase);
    const b = [{ caseId: id("B"), phase, model, wordId, arm: "B", category: "card" }];
    const a = A_CATEGORIES.map(category => ({ caseId: id("A", category), phase, model, wordId, arm: "A", category }));
    cases.push({ caseId: id("entry"), phase, model, wordId, arm: "entry", category: "entry" }, ...(flip ? [...a, ...b] : [...b, ...a]));
    if (lWords.includes(wordId)) {
      const la = { caseId: id("L-A"), phase, model, wordId, arm: "L-A", category: "literature" };
      const lb = { caseId: id("L-B"), phase, model, wordId, arm: "L-B", category: "reading" };
      cases.push(...(flip ? [lb, la] : [la, lb]));
    }
  }
  return cases;
}
export function plannedCounts(plan, evidence = null) {
  const models = Object.fromEntries(plan.models.map(model => [model.id, { clicks: 0 }]));
  for (const phase of ["probe", "pilot", "full"]) for (const row of plannedCases(plan, phase, evidence)) models[row.model].clicks++;
  for (const row of Object.values(models)) row.httpCap = Math.ceil(row.clicks * LIMITS.negotiationOverhead) + LIMITS.httpPerCase;
  return { models, clicks: Object.values(models).reduce((sum, row) => sum + row.clicks, 0) };
}

export function newLedger(plan, evidenceHash) {
  return { schema: 1, planHash: plan.planHash, evidenceHash, frozenHash: null, halted: "", spentMicros: 0,
    models: Object.fromEntries(plan.models.map(model => [model.id, { spentMicros: 0, halted: "", negotiationResends: 0, attempts: [], cases: {} }])), entries: {} };
}
const stopMicros = usd => Math.round(usd * 1e6);
export function costMicros(model, inputTokens, outputTokens) {
  return Math.ceil(inputTokens * (model.rates.inputBilled ?? model.rates.input) * 1e6 + outputTokens * model.rates.output * 1e6);
}
export function auditLedger(plan, ledger) {
  if (ledger?.schema !== 1 || ledger.planHash !== plan.planHash || !ledger.models) fail("ledger_invalid");
  let total = 0;
  for (const model of plan.models) {
    const row = ledger.models[model.id];
    if (!row || !Array.isArray(row.attempts)) fail("ledger_invalid");
    const settled = row.attempts.filter(item => item.state === "settled");
    if (settled.some(item => !Number.isSafeInteger(item.costMicros) || item.costMicros < 0) ||
        row.attempts.some(item => !Number.isSafeInteger(item.reservedMicros) || item.reservedMicros < 0 || !["reserved", "settled"].includes(item.state)) ||
        row.spentMicros !== settled.reduce((sum, item) => sum + item.costMicros, 0) ||
        row.negotiationResends !== row.attempts.filter(item => item.negotiation).length) fail("ledger_invalid");
    total += row.spentMicros;
  }
  if (ledger.spentMicros !== total) fail("ledger_invalid");
}
const outstanding = row => row.attempts.filter(item => item.state === "reserved").reduce((sum, item) => sum + item.reservedMicros, 0);
// The budget gate: pure, deterministic, run before every dispatch.
export function reserve(plan, ledger, { model: id, caseId, inputBytes, outputTokens, negotiation = null }, at = new Date().toISOString()) {
  auditLedger(plan, ledger);
  if (ledger.halted) fail("ledger_halted");
  const model = plan.models.find(row => row.id === id), row = ledger.models[id];
  if (!model) fail("unauthorized_payload");
  if (row.halted) fail(row.halted);
  if (!Number.isSafeInteger(inputBytes) || inputBytes < 1 || inputBytes > LIMITS.inputBytes ||
      !Number.isSafeInteger(outputTokens) || outputTokens < 1 || outputTokens > LIMITS.outputTokens) fail("request_bounds");
  const counts = plannedCounts(plan).models[id];
  if (row.attempts.length >= counts.httpCap || row.attempts.filter(item => item.caseId === caseId).length >= LIMITS.httpPerCase) fail("request_limit");
  const inputTokenBound = inputBytes + LIMITS.framingTokens, worst = costMicros(model, inputTokenBound, outputTokens);
  // Internal stop gates (80% of the authorized caps), not the caps themselves.
  // A round adds the settled spend of this authorization's earlier ledgers.
  const prior = plan.round?.prior;
  if ((prior?.models[id] || 0) + row.spentMicros + outstanding(row) + worst > stopMicros(model.stopUSD)) fail("cost_limit_model");
  const committed = (prior?.totalMicros || 0) + ledger.spentMicros + plan.models.reduce((sum, item) => sum + outstanding(ledger.models[item.id]), 0);
  if (committed + worst > stopMicros(plan.budget.stopUSD)) fail("cost_limit_total");
  const attempt = { n: row.attempts.length + 1, caseId, inputBytes, inputTokenBound, outputTokens, reservedMicros: worst, state: "reserved", at,
    ...(negotiation ? { negotiation } : {}) };
  row.attempts.push(attempt);
  if (negotiation) row.negotiationResends++;
  return attempt;
}
// Billed output never undercounts: some compatibility layers leave reasoning
// out of completion_tokens and only count it in total_tokens. The overrun
// check uses the same max without the separate reasoning_tokens addend, which
// may already be inside completion_tokens (cost may overcount, halts must not).
export function usageOutput(usage = {}) {
  const prompt = usage.prompt_tokens, completion = usage.completion_tokens, total = usage.total_tokens;
  const extra = Number.isSafeInteger(usage.reasoning_tokens) && !Number.isSafeInteger(usage["completion_tokens_details.reasoning_tokens"]) ? usage.reasoning_tokens : 0;
  const fromTotal = Number.isSafeInteger(total) && total > prompt ? total - prompt : 0;
  return { billed: Math.max(completion + extra, fromTotal), observed: Math.max(completion, fromTotal) };
}
export function settle(plan, ledger, attempt, { received = false, httpStatus = 0, usage = {} } = {}) {
  if (attempt.state !== "reserved") fail("ledger_invalid");
  const id = plan.models.find(model => ledger.models[model.id].attempts.includes(attempt))?.id;
  if (!id) fail("ledger_invalid");
  const model = plan.models.find(row => row.id === id), row = ledger.models[id];
  const prompt = usage?.prompt_tokens, completion = usage?.completion_tokens;
  let cost, basis, output = null;
  if (received && Number.isSafeInteger(prompt) && Number.isSafeInteger(completion)) {
    output = usageOutput(usage); cost = costMicros(model, prompt, output.billed); basis = "usage";
  } else if (received && REJECTED_BEFORE_GENERATION.includes(httpStatus)) { cost = costMicros(model, attempt.inputTokenBound, 0); basis = "rejected_input_bound"; }
  else { cost = attempt.reservedMicros; basis = "reservation"; }
  Object.assign(attempt, { state: "settled", costMicros: cost, costBasis: basis, ...(output ? { billedOutputTokens: output.billed } : {}) });
  row.spentMicros += cost; ledger.spentMicros += cost;
  if (output && (output.observed > attempt.outputTokens || prompt > attempt.inputTokenBound)) ledger.halted ||= "gateway_usage_exceeds_reservation";
  return attempt;
}
// What a resend may differ in: the parameters, never the model or messages.
// A response_format schema is kept as a hash (the ledger stays small).
export function requestSignature(body) {
  const params = {};
  for (const [field, value] of Object.entries(body || {})) if (field !== "messages" && field !== "model")
    params[field] = field === "response_format" && value && typeof value === "object" ? { type: value.type, hash: hash(value) } : value;
  return { model: body?.model, messagesHash: hash(body?.messages ?? null), params };
}
// Parameter negotiation (user ruling 2026-10-26: not a retry). A second or
// later request inside one click is admitted only directly after a 400/422
// answer to that click whose error names a parameter (the fixed labels of
// httpErrorMetadata), with the same model and messages, and with changes
// confined to the negotiable fields, one of them named. Anything else halts.
export function negotiationStep(previous, body) {
  if (!previous) return null;
  const refuse = () => fail("unexpected_resend");
  if (previous.state !== "settled" || !NEGOTIATION_STATUSES.includes(previous.httpStatus) || !previous.signature) refuse();
  const now = requestSignature(body), before = previous.signature;
  if (now.model !== before.model || now.messagesHash !== before.messagesHash) refuse();
  const fields = [...new Set([...Object.keys(before.params), ...Object.keys(now.params)])].sort();
  const changed = fields.filter(field => !isDeepStrictEqual(before.params[field], now.params[field]));
  if (!changed.length || changed.some(field => !NEGOTIABLE_FIELDS.includes(field))) refuse();
  const named = [...new Set((previous.httpError?.mentionedParameters || []).map(name => ["json_schema", "json_object", "structured_outputs"].includes(name) ? "response_format" : name))];
  if (!changed.some(field => named.includes(field))) refuse();
  return { after: previous.httpStatus, afterAttempt: previous.n, named, changed,
    removed: changed.filter(field => Object.hasOwn(before.params, field) && !Object.hasOwn(now.params, field)) };
}
// Per model, per phase: how many resends negotiation cost (listed in report).
export function negotiationSummary(plan, ledger) {
  return Object.fromEntries(plan.models.map(model => {
    const row = ledger.models[model.id], resends = row.attempts.filter(item => item.negotiation);
    const tally = values => values.reduce((acc, value) => ({ ...acc, [value]: (acc[value] || 0) + 1 }), {});
    return [model.id, { resends: row.negotiationResends, clicks: new Set(resends.map(item => item.caseId)).size,
      byPhase: tally(resends.map(item => String(item.caseId).split(":")[0])), changed: tally(resends.flatMap(item => item.negotiation.changed)),
      afterStatus: tally(resends.map(item => item.negotiation.after)), costMicros: resends.reduce((sum, item) => sum + (item.costMicros || 0), 0),
      // The refused requests that triggered a resend: the overhead negotiation adds.
      refusedCostMicros: row.attempts.filter(item => resends.some(next => next.caseId === item.caseId && next.negotiation.afterAttempt === item.n))
        .reduce((sum, item) => sum + (item.costMicros || 0), 0) }];
  }));
}
// A crash between dispatch and settlement leaves the full reservation spent.
export function recoverLedger(plan, ledger) {
  for (const model of plan.models) for (const attempt of ledger.models[model.id].attempts)
    if (attempt.state === "reserved") { settle(plan, ledger, attempt, {}); attempt.failure = "uncertain_after_crash"; }
  auditLedger(plan, ledger);
  return ledger;
}

const projection = entry => ({ word: entry.word, language: entry.language, meanings: entry.meanings.map(m => ({ partOfSpeech: m.partOfSpeech, definition: m.definition })) });
// Content whitelist per request. Anything else (articles, vocabulary, Ask
// history, a different word or a non-frozen excerpt) halts the run.
export function authorizeRequest(plan, phase, active, payload, frozen) {
  const deny = () => fail("unauthorized_payload");
  if (!active || !plan.phases[phase]?.models.includes(active.model) || !plan.phases[phase].words.includes(active.wordId)) deny();
  if (phase === "probe" && active.arm !== "entry") deny();
  const word = plan.words.find(row => row.id === active.wordId);
  if (!payload || typeof payload !== "object" || Array.isArray(payload)) deny();
  const keys = Object.keys(payload).sort(), expect = list => isDeepStrictEqual(keys, [...list].sort());
  const product = ["category", "term", "sourceLanguage", "targetLanguage", "profile", "baseEntry", "sources"];
  const shape = { entry: ["term", "sourceLanguage", "targetLanguage"], A: product, "L-A": product,
    B: ["task", "term", "sourceLanguage", "targetLanguage", "nativeLanguage", "baseEntry"],
    "L-B": ["task", "term", "sourceLanguage", "targetLanguage", "baseEntry", "source"] }[active.arm];
  if (!shape || !expect(shape) || payload.term !== word.term || payload.sourceLanguage !== word.sourceLanguage ||
      payload.targetLanguage?.lang !== word.target || typeof payload.targetLanguage?.name !== "string") deny();
  if (active.arm === "entry") return true;
  const entry = frozen?.entries?.[active.model]?.[active.wordId]?.value;
  if (!entry || !isDeepStrictEqual(payload.baseEntry, projection(entry))) deny();
  const native = SYNTHETIC_PROFILE[word.target];
  if (active.arm === "B") { if (payload.task !== "usage-card" || payload.nativeLanguage !== native) deny(); return true; }
  if (active.arm === "L-B") {
    const sentence = frozen?.evidence?.sentences?.[active.wordId];
    if (payload.task !== "sentence-reading" || !sentence || !isDeepStrictEqual(payload.source,
      { sentence: sentence.sentence, work: sentence.work, author: sentence.author, location: sentence.location })) deny();
    return true;
  }
  const category = active.arm === "L-A" ? "literature" : active.category;
  if (payload.category !== category || !isDeepStrictEqual(payload.profile, { nativeLanguage: native, level: plan.profile.level, topic: "" }) ||
      !Array.isArray(payload.sources)) deny();
  if (["literature", "etymology"].includes(category)) {
    const allowed = frozen?.evidence?.evidence?.[evidenceKey(word, category)]?.sources || [];
    if (payload.sources.some(source => !allowed.some(row => isDeepStrictEqual({ ...source, sourceIndex: undefined }, { ...row, sourceIndex: undefined })))) deny();
    if (category === "literature" && !payload.sources.length) deny();
  } else if (payload.sources.length) deny();
  return true;
}
export const evidenceKey = (word, kind) => word.sourceLanguage + ":" + word.term + ":" + kind;
export function selectLWords(plan, sentences, census) {
  const ok = id => !!sentences[id] && census[id]?.literature?.sources > 0;
  return { pilot: plan.phases.pilot.words.filter(ok), full: plan.lCandidates.filter(ok).slice(0, plan.lCount) };
}

export const HARNESS_CODES = Object.freeze(["control_missing", "interrupted", "stale", "owner_changed", "account_changed", "ai_not_configured", "ai_disabled"]);
export function failureLayer({ code = "", reason = "", finishReason = "", contentEmpty = false, httpStatus = 0 } = {}) {
  if (HARNESS_CODES.includes(code)) return "harness";
  if (["no_sources", "source_failed", "host_permission"].includes(code) || ["supplement_source", "supplement_source_index", "supplement_quote"].includes(reason)) return "evidence";
  if (code === "output_truncated" || finishReason === "length") return "truncation";
  if (code === "empty_response" || (contentEmpty && httpStatus >= 200 && httpStatus < 300)) return "empty";
  if (["request_timeout", "network", "transport_failed", "transport_timeout", "endpoint_invalid", "model_not_found", "request_failed"].includes(code) ||
      /^http_\d+$/.test(reason) || (httpStatus && (httpStatus < 200 || httpStatus >= 300))) return "transport";
  if (code === "wrong_language") return "language";
  if (["save_failed", "render_failed", "not_saved", "sync_failed"].includes(code)) return "save";
  // A required example/translation left empty is the same defect as B's
  // item_text (empty or over-limit text field): structure in both arms.
  if (code === "invalid_response" && (/^(?:response_|entry_|card_|item_|reading_)/.test(reason) ||
      ["supplement_fields", "supplement_item", "supplement_item_shape", "supplement_item_sense", "supplement_item_text", "supplement_example"].includes(reason))) return "structure";
  return "content";
}
function contentItems(text) {
  try {
    const raw = String(text).trim().replace(/^```(?:json)?[ \t]*\r?\n([\s\S]*?)\r?\n```$/i, "$1");
    let value = JSON.parse(raw);
    if (value && typeof value === "object" && Object.keys(value).length === 1 && typeof Object.values(value)[0] === "object") value = Object.values(value)[0];
    if (Array.isArray(value?.items)) return value.items.length;
    if (Array.isArray(value?.patterns) || Array.isArray(value?.contrasts)) return (value.patterns?.length || 0) + (value.contrasts?.length || 0);
    if (Array.isArray(value?.meanings)) return value.meanings.length;
    if (typeof value?.readable === "boolean") return value.readable ? 1 : 0;
  } catch {}
  return null;
}

