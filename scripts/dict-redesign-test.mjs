function caseRecord(plan, ledger, testCase, fields) {
  const attempts = ledger.models[testCase.model].attempts.filter(item => item.caseId === testCase.caseId);
  const last = attempts.at(-1) || {};
  const sum = key => attempts.reduce((total, item) => total + (Number.isSafeInteger(item.usage?.[key]) ? item.usage[key] : 0), 0);
  // C6: the same clock for every arm, the sum of this case's HTTP attempt
  // latencies. Wall time and tool overhead (mount, render, archive) apart.
  const latencyMs = attempts.reduce((total, item) => total + (Number.isFinite(item.latencyMs) ? item.latencyMs : 0), 0);
  const { wallMs = null, ...rest } = fields;
  return { ...testCase, ...rest, http: attempts.length, negotiationResends: attempts.filter(item => item.negotiation).length, httpStatuses: attempts.map(item => item.httpStatus ?? null),
    finishReasons: attempts.map(item => item.finishReason ?? null), responseModels: attempts.map(item => item.responseModel ?? null),
    usage: { prompt_tokens: sum("prompt_tokens"), completion_tokens: sum("completion_tokens"),
      output_tokens: attempts.reduce((total, item) => total + (Number.isSafeInteger(item.billedOutputTokens) ? item.billedOutputTokens
        : Number.isSafeInteger(item.usage?.completion_tokens) ? item.usage.completion_tokens : 0), 0) },
    returnedItems: fields.returnedItems ?? (attempts.findLast(item => item.httpStatus >= 200 && item.httpStatus < 300)?.returnedItems ?? null),
    latencyMs, wallMs, harnessMs: Number.isFinite(wallMs) ? Math.max(0, wallMs - latencyMs) : null,
    costMicros: attempts.reduce((total, item) => total + (item.costMicros || 0), 0), lastFinishReason: last.finishReason || "",
    cumulative: { modelMicros: ledger.models[testCase.model].spentMicros, totalMicros: ledger.spentMicros }, at: new Date().toISOString() };
}
function outcomeOf(code, reason, attempts, bridgeError) {
  if (STOP_CODES.includes(bridgeError)) return { outcome: "stopped", layer: "", code: bridgeError, reason: "" };
  const last = attempts.at(-1) || {};
  const effective = code || bridgeError || "request_failed";
  return { outcome: NEUTRAL.includes(effective) ? "neutral" : "failure", code: effective, reason,
    layer: failureLayer({ code: effective, reason, finishReason: last.finishReason, contentEmpty: last.contentEmpty, httpStatus: last.httpStatus }) };
}
// "No fallback" is checked on every answer: the response must name the
// requested model (provider prefix, case and punctuation ignored; a pure
// date suffix allowed). An absent field cannot be checked and is recorded.
export function responseModelMatches(actual, id) {
  if (!actual) return true;
  const norm = value => String(value).toLowerCase().split("/").pop().replace(/[^a-z0-9]/g, "");
  const a = norm(actual), b = norm(id);
  return a === b || (a.startsWith(b) && /^\d{6,8}$/.test(a.slice(b.length)));
}
// Pilot and full: the request ID (normalized as above) or, exactly, a name
// the model's probe reported and freeze registered.
export function responseModelAccepted(actual, id, registered = []) {
  return responseModelMatches(actual, id) || (!!actual && Array.isArray(registered) && registered.includes(actual));
}
const PLAIN_MODEL_NAME = /^[A-Za-z0-9][A-Za-z0-9._:@\/+-]{0,199}$/;
// Names each model's probe observed on 2xx answers. A name that matches a
// different authorized model (a routing fallback) or is not a plain
// identifier is reported but never accepted.
export function probeModelNames(plan, ledger) {
  return Object.fromEntries(plannedCases(plan, "probe").map(testCase => {
    const row = ledger.models[testCase.model], record = row?.cases?.[testCase.caseId] || null;
    const observed = [...new Set((row?.attempts || []).filter(item => item.caseId === testCase.caseId && item.httpStatus >= 200 && item.httpStatus < 300 &&
      typeof item.responseModel === "string" && item.responseModel).map(item => item.responseModel))];
    const rejected = observed.filter(name => !PLAIN_MODEL_NAME.test(name) ||
      plan.models.some(model => model.id !== testCase.model && responseModelMatches(name, model.id)));
    const accepted = observed.filter(name => !rejected.includes(name));
    return [testCase.model, { caseId: testCase.caseId, recorded: !!record, outcome: record?.outcome ?? null, code: record?.code || "",
      observed, accepted, rejected, aliases: accepted.filter(name => !responseModelMatches(name, testCase.model)) }];
  }));
}
