export function checkDefinitions(plan) {
  const same = { criteria: CRITERIA, generality: GENERALITY, failureLayers: FAILURE_LAYERS, neutral: NEUTRAL, thresholds: THRESHOLDS, limits: LIMITS };
  for (const [field, value] of Object.entries(same)) if (!isDeepStrictEqual(JSON.parse(JSON.stringify(value)), plan[field])) fail("definitions_changed_" + field);
  return true;
}

